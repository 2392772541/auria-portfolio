import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import {spawnSync} from 'node:child_process';
import Database from 'better-sqlite3';
const root = path.resolve(import.meta.dirname, '..');
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'auria-portable-test-'));
const run = (args, env = {}) => spawnSync(process.execPath, ['scripts/portable.mjs', ...args], {cwd: root, env: {...process.env, ...env}, encoding: 'utf8'});
const hash = data => crypto.createHash('sha256').update(data).digest('hex');
try {
  const dest = path.join(temp, 'data');
  fs.mkdirSync(path.join(dest, 'uploads'), {recursive: true});
  fs.writeFileSync(path.join(dest, 'uploads/.gitkeep'), '');
  let r = run(['restore', dest]); assert.equal(r.status, 0, r.stderr);
  const snapshot = JSON.parse(fs.readFileSync(path.join(root, 'portable/content.json')));
  const db = new Database(path.join(dest, 'auria.sqlite'));
  assert.equal(db.pragma('integrity_check', {simple: true}), 'ok');
  for (const [name, data] of Object.entries(snapshot.tables)) assert.deepEqual(db.prepare(`SELECT * FROM ${name} ORDER BY id`).all(), data.rows);
  assert.equal(db.prepare("SELECT count(*) n FROM sqlite_master WHERE name IN ('contacts','sessions')").get().n, 0);
  const serialized = JSON.stringify(snapshot);
  for (const name of new Set(serialized.match(/\/uploads\/[A-Za-z0-9._%/-]+/g) || [])) assert(fs.existsSync(path.join(dest, decodeURIComponent(name))));
  db.close();
  console.log('PASS clean skeleton restore, all rows, no private tables, upload references');
  const before = hash(fs.readFileSync(path.join(dest, 'auria.sqlite')));
  r = run(['restore', dest]); assert.notEqual(r.status, 0);
  assert.equal(hash(fs.readFileSync(path.join(dest, 'auria.sqlite'))), before);
  console.log('PASS repeat restore refuses overwrite and preserves database bytes');
  const exported = path.join(temp, 'exported');
  r = run(['export', exported], {AURIA_DATA_DIR: dest}); assert.equal(r.status, 0, r.stderr);
  assert.deepEqual(JSON.parse(fs.readFileSync(path.join(exported, 'content.json'))).tables, snapshot.tables);
  assert.deepEqual(JSON.parse(fs.readFileSync(path.join(exported, 'manifest.json'))).uploads, JSON.parse(fs.readFileSync(path.join(root, 'portable/manifest.json'))).uploads);
  console.log('PASS export/restore round trip preserves every content row and upload hash');
  r = spawnSync(process.execPath, ['scripts/backup.mjs'], {cwd: root, env: {...process.env, AURIA_DATA_DIR: dest, AURIA_BACKUP_DIR: path.join(temp, 'backups')}, encoding: 'utf8'});
  assert.equal(r.status, 0, r.stderr);
  const backupDir = path.join(temp, 'backups', fs.readdirSync(path.join(temp, 'backups'))[0]);
  const backup = new Database(path.join(backupDir, 'auria.sqlite'), {readonly: true});
  assert.equal(backup.pragma('integrity_check', {simple: true}), 'ok');
  assert.deepEqual(backup.prepare('SELECT * FROM works ORDER BY id').all(), snapshot.tables.works.rows);
  backup.close();
  console.log('PASS backup works without external sqlite3 CLI');
} finally { fs.rmSync(temp, {recursive: true, force: true}); }
